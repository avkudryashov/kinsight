#!/usr/bin/env python3
"""Cuts the ChatGPT mascot sheets (one PNG per animal, 3x2 grid of moods, see PROMPTS.md) into app drawables.

Usage: python3 scripts/brand/mascots/slice_mascots.py <folder with cat.png, dog.png, ...>
Writes core/designsystem/src/main/res/drawable-nodpi/mascot_<animal>_<mood>.webp (256x256, transparent). Needs Pillow.
"""
import os
import sys

from PIL import Image

ANIMALS = ["cat", "dog", "fox", "panda", "rabbit", "bear", "owl", "penguin", "frog", "raccoon"]  # core/model Animal order
MOODS = ["happy", "content", "calm", "worried", "upset", "unwell"]  # core/model Mood order; grid left-right, top-bottom
COLS, ROWS = 3, 2
OUT_SIZE = 256
PADDING = 0.06  # empty margin around the head inside the square, as a share of the side
ALPHA_MIN = 16  # pixels this transparent or less count as background when trimming

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..",
                   "core", "designsystem", "src", "main", "res", "drawable-nodpi")
DRAWABLE_MAP = os.path.join(OUT, "..", "..", "kotlin", "app", "kinsight", "core", "designsystem",
                            "component", "MascotDrawables.kt")


def content_box(cell: Image.Image) -> tuple[int, int, int, int] | None:
    """The bounding box of the cell's visible pixels; None for an empty cell."""
    return cell.getchannel("A").point(lambda a: 255 if a > ALPHA_MIN else 0).getbbox()


def framed_square(cell: Image.Image, box: tuple[int, int, int, int], side: int) -> Image.Image:
    """The cell's content ([box]) centred on a transparent [side]-pixel square, then scaled to OUT_SIZE. One [side] for
    all six moods of an animal keeps the head the same size in every mood (a per-cell side would shrink a mood with
    narrower ears); centring on each cell's own content keeps it centred even when the sheet's rows sit at different
    heights."""
    content = cell.crop(box)
    square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    square.paste(content, ((side - content.width) // 2, (side - content.height) // 2))
    return square.resize((OUT_SIZE, OUT_SIZE), Image.LANCZOS)


def slice_sheet(path: str, animal: str) -> list[str]:
    sheet = Image.open(path).convert("RGBA")
    if sheet.getchannel("A").getextrema()[0] == 255:
        return [f"{animal}: no transparency — ask ChatGPT for a transparent PNG background"]
    w, h = sheet.width // COLS, sheet.height // ROWS
    raw = []
    for i, mood in enumerate(MOODS):
        col, row = i % COLS, i // COLS
        cell = sheet.crop((col * w, row * h, (col + 1) * w, (row + 1) * h))
        box = content_box(cell)
        if box is None:
            return [f"{animal}: cell {i + 1} ({mood}) is empty"]
        raw.append((mood, cell, box))
    largest = max(max(b[2] - b[0], b[3] - b[1]) for _, _, b in raw)
    side = int(largest / (1 - 2 * PADDING))
    cells = [(mood, framed_square(cell, box, side)) for mood, cell, box in raw]
    os.makedirs(OUT, exist_ok=True)
    for mood, square in cells:
        square.save(os.path.join(OUT, f"mascot_{animal}_{mood}.webp"), "WEBP", quality=90, method=6)
    return []


def write_drawable_map() -> None:
    """Direct resource references for available art; absent pairs keep the vector fallback."""
    lines = [
        "package app.kinsight.core.designsystem.component", "",
        "import androidx.annotation.DrawableRes",
        "import app.kinsight.core.designsystem.R",
        "import app.kinsight.core.model.Animal",
        "import app.kinsight.core.model.Mood", "",
        "/** Raster overrides (animal avatars spec, decision 1); regenerated by slice_mascots.py. */",
        "@DrawableRes",
        "internal fun mascotDrawable(animal: Animal?, mood: Mood): Int? = when (animal) {",
        "    null -> null",
    ]
    for animal in ANIMALS:
        lines.append(f"    Animal.{animal.upper()} -> when (mood) {{")
        for mood in MOODS:
            name = f"mascot_{animal}_{mood}"
            value = f"R.drawable.{name}" if os.path.isfile(os.path.join(OUT, name + ".webp")) else "null"
            lines.append(f"        Mood.{mood.upper()} -> {value}")
        lines.append("    }")
    lines.append("}")
    with open(DRAWABLE_MAP, "w", encoding="utf-8") as output:
        output.write("\n".join(lines) + "\n")


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    folder = os.path.expanduser(sys.argv[1])
    problems, done = [], 0
    for animal in ANIMALS:
        path = os.path.join(folder, f"{animal}.png")
        if not os.path.isfile(path):
            problems.append(f"{animal}: {path} not found")
            continue
        errors = slice_sheet(path, animal)
        problems += errors
        done += 0 if errors else 1
    write_drawable_map()
    print(f"written: {done} of {len(ANIMALS)} animals ({done * len(MOODS)} images) into {os.path.normpath(OUT)}")
    for p in problems:
        print("  ! " + p)
    return 0 if not problems else 1


if __name__ == "__main__":
    sys.exit(main())
